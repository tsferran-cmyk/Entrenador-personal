// Opening a saved month never depends on the generation questionnaire.
let monthlyEntry = { status: 'idle', month: '', file: null, plan: null };
let monthlyEntryRequest = 0;
let monthlyReviewDay = '';
let monthlyEdit = null;

async function findCurrentMonthlyPlanFile() {
  const directory = extractGoogleId(directoryInput.value.trim());
  if (!directory) throw new Error('Cal validar el directori de Google Drive.');
  const files = await collectDriveFiles(directory);
  return files.find(file => file.name === getCurrentMonthAutoFileName()) || null;
}

function parseSavedMonthlyPlan(file, rows) {
  if (file.name !== getCurrentMonthAutoFileName()) throw new Error('Aquest pla ha caducat. Cal un pla del mes actual.');
  const headers = rows[0] || [];
  const routines = new Map();
  let spec = null;
  rows.slice(1).forEach(row => {
    const record = Object.fromEntries(headers.map((header, index) => [header, row[index] ?? '']));
    const name = getColumnValue(record, ['Exercici', 'Nom CA']);
    if (!name) return;
    const month = getColumnValue(record, ['Mes del pla']);
    if (month && month !== trainingCalendar().key) throw new Error('El pla conté entrenaments d’un altre mes.');
    const config = getColumnValue(record, ['Configuració del pla']);
    if (config && !spec) spec = JSON.parse(config);
    const day = String(getColumnValue(record, ['Numero', 'Número', 'Dia entrenament', 'Dia']) || '1');
    if (!routines.has(day)) routines.set(day, { day, exercises: [], duration: 0, type: '', focus: [] });
    const routine = routines.get(day);
    const modality = getColumnValue(record, ['Modalitat assignada']) ||
      (normalizeColumnName(getColumnValue(record, ['Modalitat', 'Tipus'])).includes('forca') ? 'forca' :
        normalizeColumnName(getColumnValue(record, ['Modalitat', 'Tipus'])).includes('mobilitat') ? 'mobilitat' : 'cardio');
    const assigned = String(getColumnValue(record, ['Zona assignada'])).split(';').filter(Boolean);
    routine.type = modality;
    routine.focus = assigned.length ? assigned : spec?.routines?.[Number(day) - 1]?.focus || [];
    routine.duration = Number(spec?.duration || getColumnValue(record, ['Durada', 'Durada (min)'])) || 0;
    const id = String(getColumnValue(record, ['Exercici ID', 'ID']));
    routine.exercises.push({ id, name, record, occurrence: routine.exercises.filter(item => item.id === id).length,
      assignedRegion: getColumnValue(record, ['Zona de l’exercici']), totalSeries: parseSeriesCount(getColumnValue(record, ['Sèries', 'Series'])) });
  });
  if (!routines.size) throw new Error('El pla mensual no conté cap entrenament.');
  return { file, month: trainingCalendar().key, rows, spec, routines: [...routines.values()].sort((a, b) => Number(a.day) - Number(b.day)) };
}

async function loadSavedMonthlyPlan(file) {
  const current = file || await findCurrentMonthlyPlanFile();
  if (!current) return null;
  return parseSavedMonthlyPlan(current, await readSpreadsheetRows({ ...current, cacheBust: Date.now() }));
}

async function monthlyFileForTraining(formData) {
  const file = await findCurrentMonthlyPlanFile();
  if (file) {
    if (formData.get('monthlyPlanId') && formData.get('monthlyPlanId') !== file.id) throw new Error('El pla mensual ha canviat. Torna a obrir-lo.');
    const plan = await loadSavedMonthlyPlan(file);
    monthlyEntry = { status: 'ready', month: plan.month, file, plan };
    if (plan.spec?.duration) formData.set('duration', plan.spec.duration);
    return file;
  }
  if (formData.get('monthlyExistingOnly') === '1') throw new Error('Ja no hi ha cap pla per al mes actual. Cal generar-ne un de nou.');
  return ensureAutoGeneratedTrainingFile(formData);
}

function monthlyUsageFromRows(plan, rows) {
  const headers = rows[0] || [], sessions = new Map();
  rows.slice(1).forEach((row, index) => {
    const record = Object.fromEntries(headers.map((header, column) => [header, row[column] ?? '']));
    if (!['autogenerat', 'entrenamentautogenerat'].includes(normalizeColumnName(getColumnValue(record, ['Tipus entrenament', 'Tipus'])))) return;
    const day = String(getColumnValue(record, ['Núm. entrenament', 'Dia entrenament', 'Dia']));
    if (!plan.routines.some(routine => routine.day === day)) return;
    const date = String(getColumnValue(record, ['Data']));
    if (/^\d{4}-\d{2}/.test(date) && date.slice(0, 7).replace('-', '.') !== plan.month) return;
    const sessionId = String(getColumnValue(record, ['Sessió ID'])) || date;
    if (!sessionId) return; // A row without any session identity cannot be counted reliably.
    const key = `${day}:${sessionId}`;
    if (!sessions.has(key)) sessions.set(key, { day, completed: false, performed: new Map(), expectedSets: new Map(), index });
    const session = sessions.get(key); session.index = index;
    if (normalizeColumnName(getColumnValue(record, ['Sessió completada'])) === 'si') session.completed = true;
    if (!['si', 'yes', 'completat'].includes(normalizeColumnName(getColumnValue(record, ['Completat'])))) return;
    const order = Number(getColumnValue(record, ['Ordre exercici']));
    const exerciseId = order > 0 ? `order:${order}` : String(getColumnValue(record, ['Exercici ID'])) || normalizeColumnName(getColumnValue(record, ['Exercici']));
    const set = String(getColumnValue(record, ['Sèrie', 'Sèries']));
    const number = Number(set.match(/\d+/)?.[0] || 1);
    if (!session.performed.has(exerciseId)) session.performed.set(exerciseId, new Set());
    session.performed.get(exerciseId).add(number);
    if (/\/\d+/.test(set)) session.expectedSets.set(exerciseId, Number(set.split('/')[1]));
  });
  const completed = [...sessions.values()].filter(session => session.completed || plan.routines.find(routine => routine.day === session.day).exercises.every((exercise, index) => {
    const key = session.performed.has(`order:${index + 1}`) ? `order:${index + 1}` : exercise.id || normalizeColumnName(exercise.name);
    const sets = session.performed.get(key), expected = session.expectedSets.get(key) || exercise.totalSeries;
    return sets && Array.from({ length: expected }, (_, index) => index + 1).every(number => sets.has(number));
  })).sort((a, b) => a.index - b.index);
  const counts = new Map(plan.routines.map(routine => [routine.day, 0]));
  completed.forEach(session => counts.set(session.day, counts.get(session.day) + 1));
  return { counts, lastDay: completed.at(-1)?.day || '' };
}

async function readMonthlyPlanUsage(plan) {
  const calendar = trainingCalendar();
  const files = await collectDriveFiles(extractGoogleId(directoryInput.value.trim()));
  const log = files.find(file => file.name === `${String(calendar.month).padStart(2, '0')}.${calendar.year} - Log entrenament.xlsx`);
  return monthlyUsageFromRows(plan, log ? await readSpreadsheetRows({ ...log, cacheBust: Date.now() }) : []);
}

async function nextSavedMonthlyDay(availableDays) {
  const plan = await loadSavedMonthlyPlan();
  if (!plan) throw new Error('No hi ha cap pla del mes actual.');
  const usage = await readMonthlyPlanUsage(plan);
  const days = [...availableDays].sort((a, b) => Number(a) - Number(b));
  return days[(days.indexOf(usage.lastDay) + 1) % days.length];
}

function monthlyEntryOwnsForm() {
  return monthlyEntry.month === trainingCalendar().key && ['loading', 'ready', 'error'].includes(monthlyEntry.status);
}

function syncMonthlyEntryUi() {
  const monthly = document.querySelector('[name="mode"]:checked')?.value === 'auto-generat';
  const panel = document.getElementById('monthly-plan-entry');
  if (!panel) return;
  panel.classList.toggle('hidden', !monthly || !monthlyEntryOwnsForm());
  const ready = monthlyEntry.status === 'ready';
  document.getElementById('monthly-plan-status').textContent = monthlyEntry.status === 'loading' ? 'Comprovant si ja tens un pla aquest mes…' : ready
    ? `Ja tens ${monthlyEntry.plan.routines.length} entrenaments per al mes ${monthlyEntry.month}.` : monthlyEntry.error || '';
  ['monthly-train-button', 'monthly-review-button'].forEach(id => {
    document.getElementById(id).classList.toggle('hidden', !ready);
    document.getElementById(id).disabled = !ready;
  });
  document.getElementById('monthly-retry-button').classList.toggle('hidden', monthlyEntry.status !== 'error');
}

async function refreshMonthlyEntry() {
  const request = ++monthlyEntryRequest, month = trainingCalendar().key;
  monthlyEntry = { status: 'loading', month, file: null, plan: null };
  updateWorkoutAllocationFields();
  try {
    const plan = await loadSavedMonthlyPlan();
    if (request !== monthlyEntryRequest || month !== trainingCalendar().key) return;
    monthlyEntry = plan ? { status: 'ready', month, file: plan.file, plan } : { status: 'absent', month, file: null, plan: null };
  } catch (error) {
    if (request !== monthlyEntryRequest) return;
    monthlyEntry = { status: 'error', month, file: null, plan: null, error: `No s’ha pogut comprovar el pla mensual. ${error.message}` };
  }
  updateWorkoutAllocationFields();
}

async function trainSavedMonthlyPlan() {
  const button = document.getElementById('monthly-train-button'); button.disabled = true;
  try {
    const plan = await loadSavedMonthlyPlan();
    if (!plan) throw new Error('No hi ha cap pla per al mes actual.');
    const data = new FormData(); data.set('mode', 'auto-generat'); data.set('monthlyExistingOnly', '1'); data.set('monthlyPlanId', plan.file.id);
    if (plan.spec?.duration) data.set('duration', plan.spec.duration);
    await startWorkout(data);
  } catch (error) { showWorkoutFormError(error.message); }
  finally { button.disabled = false; }
}

function monthlyElement(tag, text, className) {
  const element = document.createElement(tag); if (text) element.textContent = text; if (className) element.className = className; return element;
}

async function openMonthlyReview(day = '') {
  const status = document.getElementById('monthly-review-status');
  document.getElementById('monthly-review-panel').classList.remove('hidden'); quizPanel.classList.add('hidden');
  status.textContent = 'Carregant entrenaments…';
  try {
    const plan = await loadSavedMonthlyPlan();
    if (!plan) throw new Error('No hi ha cap pla del mes actual.');
    const usage = await readMonthlyPlanUsage(plan);
    monthlyEntry = { status: 'ready', month: plan.month, file: plan.file, plan };
    const list = document.getElementById('monthly-routine-list'); list.replaceChildren();
    document.getElementById('monthly-routine-detail').replaceChildren();
    status.textContent = `Mes ${plan.month}. Tria un entrenament per revisar-ne els exercicis.`;
    plan.routines.forEach(routine => {
      const button = monthlyElement('button', '', 'button ghost monthly-routine-card'); button.type = 'button';
      button.append(monthlyElement('strong', `Entrenament ${routine.day}`), monthlyElement('span',
        `${routine.exercises.length} exercicis · ${trainingMap[routine.type]?.label || routine.type} · ${routine.duration ? `${routine.duration} min` : 'Durada no indicada'} · Fet ${usage.counts.get(routine.day) || 0} ${(usage.counts.get(routine.day) || 0) === 1 ? 'vegada' : 'vegades'} aquest mes`));
      if (routine.focus.length) button.append(monthlyElement('span', routine.focus.map(zone => focusMap[zone] || zone).join(' + ')));
      button.addEventListener('click', () => showMonthlyRoutineDetail(routine.day)); list.append(button);
    });
    if (day && plan.routines.some(routine => routine.day === day)) showMonthlyRoutineDetail(day);
  } catch (error) { status.textContent = error.message; document.getElementById('monthly-routine-list').replaceChildren(); document.getElementById('monthly-routine-detail').replaceChildren(); }
}

function showMonthlyRoutineDetail(day) {
  monthlyReviewDay = day;
  const routine = monthlyEntry.plan.routines.find(item => item.day === day);
  const detail = document.getElementById('monthly-routine-detail'); detail.replaceChildren();
  detail.append(monthlyElement('h3', `Exercicis de l’entrenament ${day}`));
  routine.exercises.forEach((exercise, index) => {
    const card = monthlyElement('article', '', 'panel');
    card.append(monthlyElement('strong', `${index + 1}. ${exercise.name}`));
    card.append(monthlyElement('p', [focusMap[exercise.assignedRegion], getColumnValue(exercise.record, ['Material']), `${exercise.totalSeries} sèries`].filter(Boolean).join(' · ')));
    const description = getColumnValue(exercise.record, ['Descripció', 'Instruccions']);
    if (description) card.append(monthlyElement('p', description));
    const button = monthlyElement('button', 'Canviar exercici', 'button ghost'); button.type = 'button';
    button.addEventListener('click', () => openMonthlyExerciseEditor(day, index)); card.append(button); detail.append(card);
  });
}

function monthlyExerciseCandidates(plan, routine, exercise, catalog) {
  const focus = exercise.assignedRegion ? [exercise.assignedRegion] : routine.focus;
  const criteria = { trainingType: routine.type, focus, hasEquipment: plan.spec?.hasEquipment ?? true, painZones: plan.spec?.painZones || [] };
  return catalog.filter(candidate => isCatalogAvailable(candidate) && !routine.exercises.some(item => item.id === candidate.ID)
    && exerciseMatchesCriteria(candidate, criteria) && (!exercise.assignedRegion || strengthExerciseRegion(candidate) === exercise.assignedRegion));
}

async function openMonthlyExerciseEditor(day, index) {
  const status = document.getElementById('monthly-review-status');
  try {
    const plan = monthlyEntry.plan, routine = plan.routines.find(item => item.day === day), exercise = routine.exercises[index];
    if (!exercise.id) throw new Error('Aquest exercici no té ID al pla. Cal informar-lo abans de poder desar una substitució.');
    const candidates = monthlyExerciseCandidates(plan, routine, exercise, await loadExerciseCatalog());
    if (!candidates.length) throw new Error('No hi ha alternatives disponibles amb la mateixa modalitat, zona i filtres.');
    monthlyEdit = { fileId: plan.file.id, month: plan.month, day, index, exercise, candidates };
    const select = document.getElementById('monthly-exercise-choice'); select.replaceChildren();
    candidates.forEach(candidate => select.add(new Option(`${candidate['Nom CA']} · ${candidate['Material requerit']}`, candidate.ID)));
    document.getElementById('monthly-exercise-error').textContent = '';
    updateMonthlyExerciseDescription(); document.getElementById('monthly-exercise-dialog').showModal();
  } catch (error) { status.textContent = error.message; }
}

function updateMonthlyExerciseDescription() {
  const candidate = monthlyEdit?.candidates.find(item => item.ID === document.getElementById('monthly-exercise-choice').value);
  document.getElementById('monthly-exercise-description').textContent = candidate?.['Instruccions CA'] || '';
}

async function replaceSavedMonthlyExercise(edit, replacementId) {
  if (edit.month !== trainingCalendar().key) throw new Error('El pla ha caducat. Torna a obrir el mes actual.');
  const plan = await loadSavedMonthlyPlan();
  if (!plan || plan.file.id !== edit.fileId) throw new Error('El pla ha canviat. Torna a obrir-lo abans d’editar.');
  const routine = plan.routines.find(item => item.day === edit.day), exercise = routine?.exercises[edit.index];
  if (!exercise?.id) throw new Error('No es pot substituir un exercici sense ID.');
  if (!exercise || exercise.id !== edit.exercise.id) throw new Error('Aquest exercici ja ha canviat. Torna a revisar l’entrenament.');
  const replacement = monthlyExerciseCandidates(plan, routine, exercise, await loadExerciseCatalog()).find(item => item.ID === replacementId);
  if (!replacement) throw new Error('L’alternativa ja no compleix els filtres del pla.');
  const repetitions = await readCurrentRepetitions();
  const mapped = applyCurrentRepetition({ id: replacement.ID, nameCa: replacement['Nom CA'], totalSeries: 1 }, repetitions.rows, repetitions.headers);
  const values = { exerciciid: replacement.ID, id: replacement.ID, exercici: replacement['Nom CA'], nomca: replacement['Nom CA'], nomen: replacement['Nom EN'] || '',
    modalitat: replacement.Modalitat, tipus: `${getColumnValue(exercise.record, ['Fase']) || 'Entrenament principal'} - ${trainingMap[routine.type]?.label || routine.type}`,
    material: replacement['Material requerit'], materialopcional: replacement['Material opcional'] || '', descripcio: replacement['Instruccions CA'], instruccions: replacement['Instruccions CA'],
    link: replacement.Link, videoenllac: replacement.Link, zonacorporal: strengthExerciseRegion(replacement) || replacement['Zona corporal'],
    zonesprincipals: catalogGroups(replacement, routine.type), zonessecundaries: replacement['Zones secundàries'] || '', grupsmusculars: replacement['Grups musculars'], grupsarticulars: replacement['Grups articulars'],
    series: mapped.totalSeries || 1, repeticions: mapped.reps || '', pes: mapped.weight || '' };
  await editExerciseWorkbook(plan.file, rows => {
    const headers = rows[0], records = rows.slice(1).map((row, index) => ({ row: index + 1, record: Object.fromEntries(headers.map((header, column) => [header, row[column] ?? ''])) }));
    const matches = records.filter(({ record }) => String(getColumnValue(record, ['Numero', 'Número', 'Dia entrenament', 'Dia']) || '1') === edit.day && String(getColumnValue(record, ['Exercici ID', 'ID'])) === edit.exercise.id);
    const target = matches[exercise.occurrence];
    if (!target) throw new Error('El fitxer ha canviat mentre es desava. Torna a carregar-lo.');
    return headers.flatMap((header, column) => Object.hasOwn(values, normalizeColumnName(header)) ? [{ row: target.row, column, value: values[normalizeColumnName(header)] ?? '' }] : []);
  });
  let pending = null;
  try { pending = JSON.parse(localStorage.getItem(WORKOUT_STATE_KEY) || 'null'); } catch { /* Invalid local state must not mask a successful save. */ }
  if (pending?.mode === 'auto-generat' && pending.planMonth === plan.month) clearWorkoutState();
}

