function setupMonthlyHub() {
  document.getElementById('monthly-train-button')?.addEventListener('click', trainSavedMonthlyPlan);
  document.getElementById('monthly-review-button')?.addEventListener('click', () => openMonthlyReview());
  document.getElementById('monthly-retry-button')?.addEventListener('click', refreshMonthlyEntry);
  document.getElementById('monthly-review-back')?.addEventListener('click', () => {
    document.getElementById('monthly-review-panel').classList.add('hidden'); quizPanel.classList.remove('hidden'); void refreshMonthlyEntry();
  });
  document.getElementById('monthly-exercise-cancel')?.addEventListener('click', () => document.getElementById('monthly-exercise-dialog').close());
  document.getElementById('monthly-exercise-choice')?.addEventListener('change', updateMonthlyExerciseDescription);
  document.getElementById('monthly-exercise-form')?.addEventListener('submit', async event => {
    event.preventDefault(); const button = document.getElementById('monthly-exercise-save'); button.disabled = true;
    try { await replaceSavedMonthlyExercise(monthlyEdit, document.getElementById('monthly-exercise-choice').value); document.getElementById('monthly-exercise-dialog').close(); await openMonthlyReview(monthlyReviewDay); }
    catch (error) { document.getElementById('monthly-exercise-error').textContent = `No s’ha desat el canvi. ${error.message}`; }
    finally { button.disabled = false; }
  });
}
